
import streamlit as st
import torch
from PIL import Image

from app import CLASSES, CONFIDENCE_THRESHOLD, model, transform

st.set_page_config(
    page_title="Landscape Image Classifier",
    page_icon="🌳"
)

st.title("Landscape Image Classifier")
st.caption("CSC6302 Practical 7 — Computer Vision Capstone")

st.write(
    "Upload a photograph to classify it as "
    "**Buildings, Forest, or Sea**."
)

st.warning(
    "Educational demonstration only. Do not use for "
    "safety-critical decisions, environmental enforcement, "
    "or identifying individuals."
)

uploaded_file = st.file_uploader(
    "Choose a JPG or PNG photograph",
    type=["jpg", "jpeg", "png"]
)

if uploaded_file is not None:
    try:
        image = Image.open(uploaded_file).convert("RGB")
        st.image(image, caption="Uploaded image", width=450)

        if min(image.size) < 32:
            st.error("Image is too small. Please upload a clearer image.")
        elif st.button("Classify Image"):
            tensor = transform(image).unsqueeze(0)

            with torch.inference_mode():
                logits = model(tensor)
                probabilities = torch.softmax(logits, dim=1)[0]

            scores = {
                label: float(probabilities[i])
                for i, label in enumerate(CLASSES)
            }

            best_class = max(scores, key=scores.get)
            confidence = scores[best_class]

            if confidence < CONFIDENCE_THRESHOLD:
                st.warning(
                    "The model is uncertain. Please try a clearer "
                    "photograph of a building, forest, or sea."
                )
            else:
                st.success(
                    f"Prediction: {best_class.title()} "
                    f"({confidence:.1%} confidence)"
                )

            st.subheader("Class probabilities")

            for label, score in sorted(
                scores.items(),
                key=lambda item: item[1],
                reverse=True
            ):
                st.write(f"{label.title()}: {score:.1%}")
                st.progress(score)

            st.info(
                "This prediction is generated by a trained "
                "MobileNetV3 classifier and may be incorrect."
            )

    except Exception:
        st.error(
            "The image could not be processed. "
            "Please upload a valid JPG or PNG."
        )
